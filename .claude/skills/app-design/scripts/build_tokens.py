#!/usr/bin/env python3
"""Generate platform token files from one DTCG tokens.json (with app-design modes).

Usage:
  python3 build_tokens.py design/tokens/tokens.json --out design/tokens/build
  python3 build_tokens.py tokens.json --out build --only css,swift --swift-name DesignTokens

Writes:
  tokens.css    :root (light) + [data-theme="dark"] + prefers-color-scheme + prefers-contrast
                + [data-contrast="more"], so prototypes can toggle modes
  Tokens.swift  SwiftUI: colors adapt to light/dark/increased contrast (UIKit and AppKit),
                CGFloat dimensions, Double durations, font family names and weights
  Tokens.kt     Jetpack Compose: one color object per mode, dp dimensions, ms durations
  Tokens.xaml   WinUI ResourceDictionary: ThemeDictionaries Default/Dark/HighContrast + doubles
Values are resolved (references followed) per mode. Re-run after every token change.
"""
import argparse
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import tokens_lib as tl  # noqa: E402

SKIP_PRIMITIVES = True


def skip(path):
    return SKIP_PRIMITIVES and tl.is_primitive(path)


HEADER = "Generated by app-design/scripts/build_tokens.py from %s. Do not edit; change tokens.json and re-run."


# ---------------------------------------------------------------- CSS

def css_value(token_type, value):
    if token_type == "color":
        return tl.to_hex(tl.parse_color(value))
    if token_type == "dimension":
        return value if isinstance(value, str) else tl.fmt(tl.number(value)) + "px"
    if token_type == "duration":
        return value if isinstance(value, str) else tl.fmt(tl.number(value)) + "ms"
    if token_type == "fontFamily":
        names = value if isinstance(value, list) else [value]
        generic = {"serif", "sans-serif", "monospace", "system-ui", "ui-sans-serif", "ui-serif",
                   "ui-monospace", "ui-rounded", "cursive", "-apple-system", "BlinkMacSystemFont"}
        return ", ".join(n if n in generic or " " not in n else '"%s"' % n for n in names)
    if token_type == "cubicBezier":
        return "cubic-bezier(%s)" % ", ".join(tl.fmt(float(v)) for v in value)
    if token_type == "shadow":
        layers = value if isinstance(value, list) else [value]
        parts = []
        for s in layers:
            parts.append("%s%s %s %s %s %s" % (
                "inset " if s.get("inset") else "",
                css_value("dimension", s.get("offsetX", 0)), css_value("dimension", s.get("offsetY", 0)),
                css_value("dimension", s.get("blur", 0)), css_value("dimension", s.get("spread", 0)),
                css_value("color", s.get("color", "#000000"))))
        return ", ".join(parts)
    if isinstance(value, (list, dict)):
        return json.dumps(value)
    return str(value)


def css_entries(tokens, mode, only_mode_dependent, modes, skip_primitives=False):
    lines = []
    for path, token in tokens.items():
        if skip_primitives and tl.is_primitive(path):
            continue
        t = token.get("$type")
        if only_mode_dependent and not tl.depends_on_mode(tokens, path, modes):
            continue
        value = tl.resolve(tokens, path, mode)
        if t == "typography" and isinstance(value, dict):
            for key, sub_type in (("fontFamily", "fontFamily"), ("fontSize", "dimension"), ("fontWeight", None),
                                  ("lineHeight", None), ("letterSpacing", "dimension")):
                if key in value:
                    sub = tl.resolve_value(tokens, value[key], mode)
                    lines.append("  --%s-%s: %s;" % (tl.kebab(path), tl.kebab(key), css_value(sub_type, sub)))
            continue
        lines.append("  --%s: %s;" % (tl.kebab(path), css_value(t, value)))
    return lines


def build_css(tokens, modes, src, skip_primitives=False):
    out = ["/* " + HEADER % src + " */", "", ":root {"] + css_entries(tokens, "light", False, modes, skip_primitives) + ["}"]

    def block(selector, mode, media=None):
        body = css_entries(tokens, mode, True, modes, skip_primitives)
        if not body:
            return []
        if media:
            return ["", "@media %s {" % media, "  %s {" % selector] + ["  " + b for b in body] + ["  }", "}"]
        return ["", "%s {" % selector] + body + ["}"]

    if "dark" in modes:
        out += block('[data-theme="dark"]', "dark")
        out += block(':root:not([data-theme="light"])', "dark", "(prefers-color-scheme: dark)")
    if "high-contrast" in modes:
        out += block('[data-contrast="more"]', "high-contrast")
        out += block(':root:not([data-contrast="standard"])', "high-contrast", "(prefers-contrast: more)")
    if "dark-high-contrast" in modes:
        out += block('[data-theme="dark"][data-contrast="more"]', "dark-high-contrast")
        out += block(':root:not([data-theme="light"]):not([data-contrast="standard"])', "dark-high-contrast",
                     "(prefers-color-scheme: dark) and (prefers-contrast: more)")
    return "\n".join(out) + "\n"


# ---------------------------------------------------------------- Swift

def swift_color(rgba):
    r, g, b, a = rgba
    return "RGBA(%.4f, %.4f, %.4f, %.4f)" % (r, g, b, a)


def build_swift(tokens, modes, src, name):
    colors, dims, durs, fams, weights, curves = [], [], [], [], [], []
    for path, token in tokens.items():
        t = token.get("$type")
        if skip(path):
            continue
        ident = tl.camel(path, drop_first=(t == "color"))
        if t == "color":
            vals = {m: tl.parse_color(tl.resolve(tokens, path, m)) for m in modes}
            light = vals["light"]
            dark = vals.get("dark", light)
            hc = vals.get("high-contrast", light)
            dhc = vals.get("dark-high-contrast", dark)
            colors.append("        /// %s\n        static let %s = SwiftUI.Color.adaptive(light: %s, dark: %s, lightHighContrast: %s, darkHighContrast: %s)"
                          % (path, ident, swift_color(light), swift_color(dark), swift_color(hc), swift_color(dhc)))
        elif t in ("dimension", "number"):
            try:
                dims.append("        static let %s: CGFloat = %s  // %s" % (ident, tl.fmt(tl.number(tl.resolve(tokens, path, "light"))), path))
            except ValueError:
                pass
        elif t == "duration":
            durs.append("        static let %s: Double = %s  // seconds, %s" % (ident, tl.fmt(tl.number(tl.resolve(tokens, path, "light")) / 1000), path))
        elif t == "fontFamily":
            v = tl.resolve(tokens, path, "light")
            names = v if isinstance(v, list) else [v]
            if names and names[0] in tl.SYSTEM_FONT_NAMES:
                fams.append('        static let %s: String? = nil  // system font (SF Pro); %s' % (ident, path))
            else:
                first = next((n for n in names if not n.startswith("-") and n not in ("serif", "sans-serif", "monospace")), names[0])
                fams.append('        static let %s: String? = "%s"  // %s' % (ident, first, path))
        elif t == "fontWeight":
            weights.append("        static let %s: CGFloat = %s  // %s (100-900)" % (ident, tl.fmt(tl.number(tl.resolve(tokens, path, "light"))), path))
        elif t == "cubicBezier":
            v = tl.resolve(tokens, path, "light")
            curves.append("        static let %s = UnitCurve.bezier(startControlPoint: UnitPoint(x: %s, y: %s), endControlPoint: UnitPoint(x: %s, y: %s))  // %s"
                          % (ident, *[tl.fmt(float(x)) for x in v], path))

    def section(title, lines):
        return ["", "    enum %s {" % title] + (lines or ["        // none"]) + ["    }"]

    out = ["// " + HEADER % src, "", "import SwiftUI", "#if canImport(UIKit)", "import UIKit", "#elseif canImport(AppKit)", "import AppKit", "#endif", "",
           "enum %s {" % name]
    out += section("Colors", colors) + section("Dimensions", dims) + section("Durations", durs)
    out += section("FontFamilies", fams) + section("FontWeights", weights) + section("Curves", curves)
    out += ["}", "",
            "struct RGBA { let r, g, b, a: Double; init(_ r: Double, _ g: Double, _ b: Double, _ a: Double) { self.r = r; self.g = g; self.b = b; self.a = a } }",
            "",
            "extension SwiftUI.Color {",
            "    /// A color that follows light/dark appearance and Increase Contrast.",
            "    static func adaptive(light: RGBA, dark: RGBA, lightHighContrast: RGBA, darkHighContrast: RGBA) -> SwiftUI.Color {",
            "        #if canImport(UIKit)",
            "        return SwiftUI.Color(uiColor: UIColor { traits in",
            "            let isDark = traits.userInterfaceStyle == .dark",
            "            let isHigh = traits.accessibilityContrast == .high",
            "            let c = isDark ? (isHigh ? darkHighContrast : dark) : (isHigh ? lightHighContrast : light)",
            "            return UIColor(red: c.r, green: c.g, blue: c.b, alpha: c.a)",
            "        })",
            "        #elseif canImport(AppKit)",
            "        return SwiftUI.Color(nsColor: NSColor(name: nil) { appearance in",
            "            let match = appearance.bestMatch(from: [.aqua, .darkAqua, .accessibilityHighContrastAqua, .accessibilityHighContrastDarkAqua])",
            "            let c: RGBA",
            "            switch match {",
            "            case .darkAqua: c = dark",
            "            case .accessibilityHighContrastAqua: c = lightHighContrast",
            "            case .accessibilityHighContrastDarkAqua: c = darkHighContrast",
            "            default: c = light",
            "            }",
            "            return NSColor(srgbRed: c.r, green: c.g, blue: c.b, alpha: c.a)",
            "        })",
            "        #endif",
            "    }",
            "}"]
    return "\n".join(out) + "\n"


# ---------------------------------------------------------------- Kotlin / Compose

def kt_color(rgba):
    r, g, b, a = rgba
    return "Color(0x%02X%02X%02X%02X)" % (round(a * 255), round(r * 255), round(g * 255), round(b * 255))


def build_kotlin(tokens, modes, src, package):
    color_paths = [p for p, t in tokens.items() if t.get("$type") == "color" and not skip(p)]
    out = ["// " + HEADER % src, "package " + package, "",
           "import androidx.compose.runtime.Immutable", "import androidx.compose.ui.graphics.Color",
           "import androidx.compose.ui.unit.dp", "import androidx.compose.ui.unit.sp", "",
           "@Immutable", "data class TokenColors("]
    out += ["    val %s: Color," % tl.camel(p, drop_first=True) for p in color_paths]
    out += [")", ""]
    for mode in modes:
        obj = "TokenColors" + "".join(w.capitalize() for w in mode.split("-"))
        out.append("val %s = TokenColors(" % obj)
        out += ["    %s = %s," % (tl.camel(p, drop_first=True), kt_color(tl.parse_color(tl.resolve(tokens, p, mode)))) for p in color_paths]
        out += [")", ""]
    out.append("object TokenDimens {")
    for path, token in tokens.items():
        t, ident = token.get("$type"), tl.camel(path)
        try:
            v = tl.resolve(tokens, path, "light")
            if t in ("dimension", "number"):
                unit = "sp" if path.startswith(("font", "type", "text")) and "size" in path.lower() else "dp"
                out.append("    val %s = %s.%s  // %s" % (ident, tl.fmt(tl.number(v)), unit, path))
            elif t == "duration":
                out.append("    const val %sMs = %d  // %s" % (ident, round(tl.number(v)), path))
            elif t == "fontWeight":
                out.append("    const val %s = %d  // %s" % (ident, round(tl.number(v)), path))
        except ValueError:
            continue
    out.append("}")
    return "\n".join(out) + "\n"


# ---------------------------------------------------------------- XAML (WinUI)

def build_xaml(tokens, modes, src):
    color_paths = [p for p, t in tokens.items() if t.get("$type") == "color" and not skip(p)]

    def theme(key, mode):
        lines = ['        <ResourceDictionary x:Key="%s">' % key]
        for p in color_paths:
            rgba = tl.parse_color(tl.resolve(tokens, p, mode))
            hexv = "#%02X%02X%02X%02X" % (round(rgba[3] * 255), round(rgba[0] * 255), round(rgba[1] * 255), round(rgba[2] * 255))
            name = tl.pascal(p)
            lines.append('            <Color x:Key="%sColor">%s</Color>' % (name, hexv))
            lines.append('            <SolidColorBrush x:Key="%sBrush" Color="{StaticResource %sColor}" />' % (name, name))
        lines.append("        </ResourceDictionary>")
        return lines

    out = ['<!-- ' + HEADER % src + ' -->',
           '<ResourceDictionary xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation"',
           '                    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">',
           "    <ResourceDictionary.ThemeDictionaries>"]
    out += theme("Default", "light")
    if "dark" in modes:
        out += theme("Dark", "dark")
    if "high-contrast" in modes:
        out.append("        <!-- Prefer system colors (SystemColorWindowColor, SystemColorButtonTextColor...) in HighContrast; these are fallbacks. -->")
        out += theme("HighContrast", "high-contrast")
    out.append("    </ResourceDictionary.ThemeDictionaries>")
    for path, token in tokens.items():
        if token.get("$type") in ("dimension", "number", "fontWeight"):
            try:
                out.append('    <x:Double x:Key="%s">%s</x:Double>' % (tl.pascal(path), tl.fmt(tl.number(tl.resolve(tokens, path, "light")))))
            except ValueError:
                pass
    out.append("</ResourceDictionary>")
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("tokens")
    ap.add_argument("--out", default="build")
    ap.add_argument("--only", default="css,swift,kotlin,xaml", help="comma list of css,swift,kotlin,xaml")
    ap.add_argument("--swift-name", default="Tokens")
    ap.add_argument("--kotlin-package", default="design.tokens")
    ap.add_argument("--include-primitives", action="store_true", help="also emit primitive colors in Swift/Kotlin/XAML")
    ap.add_argument("--no-css-primitives", action="store_true", help="leave primitives out of tokens.css too")
    args = ap.parse_args()

    tree = tl.load(args.tokens)
    all_tokens = tl.flatten(tree)
    modes, _ = tl.settings(tree)
    src = os.path.basename(args.tokens)
    # Screens and app code use semantic tokens only, so primitives stay out of platform files
    # (they remain in tokens.css as --color-primitive-* unless --no-css-primitives).
    global SKIP_PRIMITIVES
    SKIP_PRIMITIVES = not args.include_primitives
    tokens = all_tokens
    platform_count = sum(1 for p in all_tokens if not tl.is_primitive(p))
    os.makedirs(args.out, exist_ok=True)
    wanted = {w.strip() for w in args.only.split(",")}
    jobs = [("css", "tokens.css", lambda: build_css(tokens, modes, src, skip_primitives=args.no_css_primitives)),
            ("swift", args.swift_name + ".swift", lambda: build_swift(tokens, modes, src, args.swift_name)),
            ("kotlin", "Tokens.kt", lambda: build_kotlin(tokens, modes, src, args.kotlin_package)),
            ("xaml", "Tokens.xaml", lambda: build_xaml(tokens, modes, src))]
    for key, filename, fn in jobs:
        if key in wanted:
            path = os.path.join(args.out, filename)
            with open(path, "w", encoding="utf-8") as f:
                f.write(fn())
            print("wrote", path)
    print("%d tokens (%d semantic), modes: %s" % (len(all_tokens), platform_count, ", ".join(modes)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
